// ============================================================
// Module      : control_memory
// Description : Completed microprogram for Project 1
// ============================================================

module control_memory (
    input  wire [7:0]  address,
    output reg  [31:0] microinstruction
);

    reg [31:0] rom [0:255];

    // Bit encoding (31→16):
    // 31 AR_Load | 30 AR_Inc | 29 PC_Load | 28 PC_Inc
    // 27 DR_Load | 26 AC_Load | 25 IR_Load | 24 Mem_Write
    // 23 ALU_Add | 22 ALU_And | 21 ALU_DR
    // 20-18 Bus_Select (001=AR, 010=PC, 011=DR, 100=AC, 101=IR, 111=Mem)

    initial begin
        integer i;
        for (i = 0; i < 256; i = i + 1)
            rom[i] = 32'h0000_0000;

        // ==================== FETCH ====================
        rom[8'h00] = 32'b1000_0000_0000_1000_0000_0000_0000_0000; // AR ← PC
        rom[8'h01] = 32'b0001_0010_0001_1100_0000_0000_0000_0000; // IR ← M[AR], PC++
        rom[8'h02] = 32'b1000_0000_0001_0100_0000_0000_0000_0000; // AR ← IR[11:0]
        rom[8'h03] = 32'b0000_0000_0000_0000_0000_0100_0000_0000; // MAP

        // ==================== INDIRECT ====================
        rom[8'h08] = 32'b0000_1000_0001_1100_0000_0000_0000_0000; // DR ← M[AR]
        rom[8'h09] = 32'b1000_0000_0000_1100_0000_0001_0000_0011; // AR ← DR, JUMP to MAP

        // ==================== AND ====================
        rom[8'h10] = 32'b0000_1000_0001_1100_0000_0000_0000_0000; // DR ← M[AR]
        rom[8'h11] = 32'b0000_0100_0100_0000_0000_0001_0000_0000; // AC ← AC ∧ DR, JUMP 0

        // ==================== ADD ====================
        rom[8'h18] = 32'b0000_1000_0001_1100_0000_0000_0000_0000; // DR ← M[AR]
        rom[8'h19] = 32'b0000_0100_1000_0000_0000_0001_0000_0000; // AC ← AC + DR, JUMP 0

        // ==================== LDA ====================
        rom[8'h20] = 32'b0000_1000_0001_1100_0000_0000_0000_0000; // DR ← M[AR]
        rom[8'h21] = 32'b0000_0100_0010_0000_0000_0001_0000_0000; // AC ← DR, JUMP 0

        // ==================== STA ====================
        rom[8'h28] = 32'b0000_0001_0001_0000_0000_0001_0000_0000; // M[AR] ← AC, JUMP 0

        // ==================== BUN ====================
        rom[8'h30] = 32'b0010_0000_0000_0100_0000_0001_0000_0000; // PC ← AR, JUMP 0

        // ==================== BSA ====================
        rom[8'h38] = 32'b0000_0001_0000_0100_0000_0000_0000_0000; // M[AR] ← PC
        rom[8'h39] = 32'b0100_0000_0000_0000_0000_0000_0000_0000; // AR ← AR + 1
        rom[8'h3A] = 32'b0010_0000_0000_0100_0000_0001_0000_0000; // PC ← AR, JUMP 0

        // ==================== ISZ (simplified) ==========
        rom[8'h40] = 32'b0000_1000_0001_1100_0000_0000_0000_0000; // DR ← M[AR]
        rom[8'h41] = 32'b0000_0000_0000_0000_0000_0000_0000_0000; // (DR increment not fully wired yet)
        rom[8'h42] = 32'b0000_0001_0001_1100_0000_0000_0000_0000; // M[AR] ← DR
        rom[8'h43] = 32'b0000_0000_0000_0000_0000_0001_0000_0000; // JUMP 0

        // ==================== Register-reference / HLT =========
        // For simplicity we currently treat all opcode 111 as HLT.
        // Individual CLA/CMA/INC can be added later by decoding IR[11:0].
        rom[8'h48] = 32'b0000_0000_0000_0000_0000_0001_0100_1000; // HLT (jump to self)
    end

    always @(*) begin
        microinstruction = rom[address];
    end

endmodule