// ============================================================
// Module      : control_memory
// Description : 256 x 32-bit ROM containing the microprogram
// ============================================================

module control_memory (
    input  wire [7:0]  address,
    output reg  [31:0] microinstruction
);

    reg [31:0] rom [0:255];

    initial begin
        integer i;
        for (i = 0; i < 256; i = i + 1)
            rom[i] = 32'h0000_0000;

        // ====================================================
        // FETCH CYCLE
        // ====================================================

        // 0x00 : AR ← PC          (Bus ← PC, AR_Load)
        rom[8'h00] = 32'b0010_0000_0000_0010_0000_0000_0000_0000;

        // 0x01 : IR ← M[AR], PC ← PC+1
        //        (Bus ← Mem, IR_Load, PC_Inc)
        rom[8'h01] = 32'b0000_0001_0000_0001_0000_0000_0000_0000;

        // 0x02 : AR ← IR[11:0]    (simplified for now)
        rom[8'h02] = 32'b1000_0000_0000_0000_0000_0000_0000_0000;

        // 0x03 : MAP
        rom[8'h03] = 32'b0000_0000_0000_0000_0000_0011_0000_0000;  // Seq = MAP

        // ====================================================
        // AND  (starts at 0x10)
        // ====================================================
        // 0x10 : DR ← M[AR]
        rom[8'h10] = 32'b0000_0100_0000_0001_0000_0000_0000_0000;
        // 0x11 : AC ← AC ∧ DR , go to Fetch
        rom[8'h11] = 32'b0000_0010_0100_0000_0000_0001_0000_0000;

        // ====================================================
        // ADD  (starts at 0x18)
        // ====================================================
        rom[8'h18] = 32'b0000_0100_0000_0001_0000_0000_0000_0000; // DR ← M[AR]
        rom[8'h19] = 32'b0000_0010_1000_0000_0000_0001_0000_0000; // AC ← AC + DR

        // ====================================================
        // LDA  (starts at 0x20)
        // ====================================================
        rom[8'h20] = 32'b0000_0100_0000_0001_0000_0000_0000_0000; // DR ← M[AR]
        rom[8'h21] = 32'b0000_0010_0010_0000_0000_0001_0000_0000; // AC ← DR

        // ====================================================
        // STA  (starts at 0x28)
        // ====================================================
        rom[8'h28] = 32'b0000_0000_1000_1000_0000_0001_0000_0000; // M[AR] ← AC

        // ====================================================
        // BUN  (starts at 0x30)
        // ====================================================
        rom[8'h30] = 32'b0010_0000_0000_0000_0000_0001_0000_0000; // PC ← AR

        // More instructions will be added later (BSA, ISZ, Register-ref...)
    end

    always @(*) begin
        microinstruction = rom[address];
    end

endmodule