// ============================================================
// Module      : control_memory
// Description : 256 x 32-bit ROM - Microprogram (Clean Encoding)
// ============================================================

module control_memory (
    input  wire [7:0]  address,
    output reg  [31:0] microinstruction
);

    reg [31:0] rom [0:255];

    // ------------------------------------------------------------
    // Bit encoding (bits 31 downto 16) used from now on:
    // 31: AR_Load
    // 30: AR_Inc
    // 29: PC_Load
    // 28: PC_Inc
    // 27: DR_Load
    // 26: AC_Load
    // 25: IR_Load
    // 24: Mem_Write
    // 23: ALU_Add
    // 22: ALU_And
    // 21: ALU_DR          (AC ← DR)
    // 20-18: Bus_Select[2:0]
    //        001 = AR, 010 = PC, 011 = DR, 100 = AC, 101 = IR, 111 = Memory
    // ------------------------------------------------------------

    initial begin
        integer i;
        for (i = 0; i < 256; i = i + 1)
            rom[i] = 32'h0000_0000;

        // ===================== FETCH CYCLE =====================
        // 0x00: Bus ← PC, AR ← Bus
        rom[8'h00] = 32'b1000_0000_0000_1000_0000_0000_0000_0000; // AR_Load + Bus=PC (010)

        // 0x01: Bus ← Memory, IR ← Bus, PC ← PC+1
        rom[8'h01] = 32'b0001_0010_0001_1100_0000_0000_0000_0000; // IR_Load + PC_Inc + Bus=Mem

        // 0x02: Bus ← IR, AR ← Bus
        rom[8'h02] = 32'b1000_0000_0001_0100_0000_0000_0000_0000; // AR_Load + Bus=IR

        // 0x03: MAP
        rom[8'h03] = 32'b0000_0000_0000_0000_0000_0011_0000_0000; // Seq = MAP

                // ===================== AND (0x10) ======================
        // 0x10: Bus ← Mem, DR ← Bus
        rom[8'h10] = 32'b0000_0100_0001_1100_0000_0000_0000_0000;
        // 0x11: AC ← AC ∧ DR , JUMP to 0x00   (no IR_Load!)
        rom[8'h11] = 32'b0000_0010_0100_0000_0000_0001_0000_0000;

        // ===================== ADD (0x18) ======================
        // 0x18: Bus ← Mem, DR ← Bus
        rom[8'h18] = 32'b0000_0100_0001_1100_0000_0000_0000_0000;
        // 0x19: AC ← AC + DR , JUMP to 0x00
        rom[8'h19] = 32'b0000_0010_1000_0000_0000_0001_0000_0000;

        // ===================== LDA (0x20) ======================
        // 0x20: Bus ← Mem, DR ← Bus
        rom[8'h20] = 32'b0000_0100_0001_1100_0000_0000_0000_0000;
        // 0x21: AC ← DR , JUMP to 0x00
        rom[8'h21] = 32'b0000_0010_0010_0000_0000_0001_0000_0000;

        // ===================== STA (0x28) ======================
        rom[8'h28] = 32'b0000_0000_1001_0000_0000_0001_0000_0000;

        // ===================== BUN (0x30) ======================
        rom[8'h30] = 32'b0010_0000_0000_0100_0000_0001_0000_0000;

    always @(*) begin
        microinstruction = rom[address];
    end

endmodule