// ============================================================
// Module      : control_memory
// Description : Expanded microprogram
// ============================================================

module control_memory (
    input  wire [7:0]  address,
    output reg  [31:0] microinstruction
);

    reg [31:0] rom [0:255];

    initial begin
        integer i;
        for (i = 0; i < 256; i = i + 1)
            rom[i] = 32'h0000_0000;

        // ========== FETCH ==========
        rom[8'h00] = 32'b1000_0000_0000_1000_0000_0000_0000_0000; // AR ← PC
        rom[8'h01] = 32'b0001_0010_0001_1100_0000_0000_0000_0000; // IR ← M[AR], PC++
        rom[8'h02] = 32'b1000_0000_0001_0100_0000_0000_0000_0000; // AR ← IR[11:0]
        rom[8'h03] = 32'b0000_0000_0000_0000_0000_0011_0000_0000; // MAP

        // ========== AND ==========
        rom[8'h10] = 32'b0000_1000_0001_1100_0000_0000_0000_0000; // DR ← M[AR]
        rom[8'h11] = 32'b0000_0100_0100_0000_0000_0001_0000_0000; // AC ← AC ∧ DR

        // ========== ADD ==========
        rom[8'h18] = 32'b0000_1000_0001_1100_0000_0000_0000_0000; // DR ← M[AR]
        rom[8'h19] = 32'b0000_0100_1000_0000_0000_0001_0000_0000; // AC ← AC + DR

        // ========== LDA ==========
        rom[8'h20] = 32'b0000_1000_0001_1100_0000_0000_0000_0000; // DR ← M[AR]
        rom[8'h21] = 32'b0000_0100_0010_0000_0000_0001_0000_0000; // AC ← DR

        // ========== STA ==========
        rom[8'h28] = 32'b0000_0001_0001_0000_0000_0001_0000_0000; // M[AR] ← AC

        // ========== BUN ==========
        rom[8'h30] = 32'b0010_0000_0000_0100_0000_0001_0000_0000; // PC ← AR

        // ========== BSA ==========
        rom[8'h38] = 32'b0000_0001_0000_0100_0000_0000_0000_0000; // M[AR] ← PC
        rom[8'h39] = 32'b0100_0000_0000_0000_0000_0000_0000_0000; // AR ← AR + 1
        rom[8'h3A] = 32'b0010_0000_0000_0100_0000_0001_0000_0000; // PC ← AR

        // ========== ISZ (simplified) ==========
        rom[8'h40] = 32'b0000_1000_0001_1100_0000_0000_0000_0000; // DR ← M[AR]
        rom[8'h41] = 32'b0000_0000_0000_0000_0000_0000_0000_0000; // (DR++ not fully implemented yet)
        rom[8'h42] = 32'b0000_0001_0001_1100_0000_0000_0000_0000; // M[AR] ← DR
        rom[8'h43] = 32'b0000_0000_0000_0000_0000_0001_0000_0000; // JUMP 0

        // ========== Register-ref / HLT ==========
        rom[8'h48] = 32'b0000_0000_0000_0000_0000_0001_0100_1000; // HLT loop
    end

    always @(*) begin
        microinstruction = rom[address];
    end

endmodule