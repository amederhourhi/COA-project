// ============================================================
// Module      : control_memory
// Description : 256 x 32-bit ROM containing the microprogram
// ============================================================

module control_memory (
    input  wire [7:0]  address,
    output reg  [31:0] microinstruction
);

    reg [31:0] rom [0:255];

        initial begin
        // Clear entire memory
        for (integer i = 0; i < 256; i = i + 1) begin
            rom[i] = 32'h0000_0000;
        end

                // ====================================================
        // FETCH CYCLE
        // ====================================================
        // 0x00 : Bus ← PC, AR ← Bus
        // Bus_Select = 010 (PC), AR_Load = 1
        rom[8'h00] = 32'b1000_0000_0000_1000_0000_0000_0000_0000; // AR_Load + Bus=PC

        // 0x01 : Bus ← Memory, IR ← Bus, PC ← PC+1
        // Bus_Select = 111 (Mem), IR_Load = 1, PC_Inc = 1
        rom[8'h01] = 32'b0001_0010_0001_1100_0000_0000_0000_0000;

        // 0x02 : Bus ← IR, AR ← Bus   (AR ← address part of IR)
        // Bus_Select = 101 (IR), AR_Load = 1
        rom[8'h02] = 32'b1000_0000_0001_0100_0000_0000_0000_0000;

        // 0x03 : MAP
        rom[8'h03] = 32'b0000_0000_0000_0000_0000_0011_0000_0000;

        // ====================================================
        // AND (start 0x10)
        // ====================================================
        // 0x10 : Bus ← Mem, DR ← Bus
        rom[8'h10] = 32'b0000_0100_0001_1100_0000_0000_0000_0000;
        // 0x11 : AC ← AC ∧ DR , JUMP to Fetch
        rom[8'h11] = 32'b0000_0010_0100_0000_0000_0001_0000_0000;

        // ====================================================
        // ADD (0x18)
        // ====================================================
        rom[8'h18] = 32'b0000_0100_0001_1100_0000_0000_0000_0000; // DR ← M[AR]
        rom[8'h19] = 32'b0000_0010_1000_0000_0000_0001_0000_0000; // AC ← AC+DR

        // ====================================================
        // LDA (0x20)
        // ====================================================
        rom[8'h20] = 32'b0000_0100_0001_1100_0000_0000_0000_0000; // DR ← M[AR]
        rom[8'h21] = 32'b0000_0010_0010_0000_0000_0001_0000_0000; // AC ← DR

        // ====================================================
        // STA (0x28)
        // ====================================================
        // Bus ← AC, Mem_Write
        rom[8'h28] = 32'b0000_0000_1001_0000_0000_0001_0000_0000;

        // ====================================================
        // BUN (0x30)
        // ====================================================
        // Bus ← AR, PC ← Bus
        rom[8'h30] = 32'b0010_0000_0000_0100_0000_0001_0000_0000;

    always @(*) begin
        microinstruction = rom[address];
    end

endmodule